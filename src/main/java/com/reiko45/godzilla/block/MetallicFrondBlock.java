/** Metallic flora from the anime trilogy's far-future Earth: plants whose tissue grew metal under Godzilla's reign. */
public class MetallicFrondBlock extends net.minecraft.world.level.block.BushBlock {
    public static final MapCodec<MetallicFrondBlock> CODEC = simpleCodec(MetallicFrondBlock::new);
    private static final VoxelShape SHAPE = Block.box(2, 0, 2, 14, 14, 14);

    public MetallicFrondBlock(Properties properties) {
        super(properties);
    }

    @Override
    protected MapCodec<MetallicFrondBlock> codec() {
        return CODEC;
    }

    @Override
    protected VoxelShape getShape(BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return SHAPE;
    }

    @Override
    protected boolean mayPlaceOn(BlockState state, BlockGetter level, BlockPos pos) {
        return state.isFaceSturdy(level, pos, Direction.UP);
    }

    @Override
    public void animateTick(BlockState state, Level level, BlockPos pos, RandomSource random) {
        if (random.nextInt(25) == 0) level.addParticle(ParticleTypes.ELECTRIC_SPARK, pos.getX() + random.nextDouble(), pos.getY() + 0.8, pos.getZ() + random.nextDouble(), 0, 0.01, 0);
    }
}
